# Writes link-rules.json (python3 -I link_rules.py > link-rules.json): the Bluetooth link rules of PROTOCOL-v2
# "Bluetooth link" as cases both apps run. Keys and sid from the OGS draft-1 vectors (throwaway values).
import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OGS = json.load(open(os.path.join(HERE, "..", "ogs", "ogs-draft1.json")))
SID = OGS["sid"]
OURS = OGS["keys"]["I"]["pub"]
OTHER = OGS["keys"]["X"]["pub"]
ATTRIBUTE, HEADER, MIN_PAYLOAD = 512, 6, 14


def m(sid, nonce):
    return hashlib.sha256(f"cgm2:ble:{sid}:{nonce}".encode()).hexdigest()[:32]


def nonce(label):
    return hashlib.sha256(f"sukrara/ble/link-rules nonce: {label}".encode()).hexdigest()[:32]


N = [nonce(str(k)) for k in range(5)]  # N[0] is older than the 4 the follower keeps
KEPT = N[1:]


def info(nonce_=None, m_=None, i=None):
    o = {"v": 2}
    if nonce_ is not None:
        o["nonce"] = nonce_
    if m_ is not None:
        o["m"] = m_
    if i is not None:
        o["i"] = i
    return o


def case(name, info_, expect, sid=True, identity=True):
    return {"name": name, "identity": OURS if identity else None, "sid": SID if sid else None, "nonces": KEPT,
            "info": info_, "expect": expect}


owner = [
    case("sid known: m over our newest nonce", info(N[4], m(SID, N[4])), "ours"),
    case("sid known: m over the oldest of our last 4 nonces", info(N[1], m(SID, N[1])), "ours"),
    case("sid known: m over our nonce, our i (the wearer pairing nearby)", info(N[4], m(SID, N[4]), OURS), "ours"),
    case("sid known: m over a nonce we no longer keep (a recorded INFO)", info(N[0], m(SID, N[0])), "other"),
    case("sid known: m over another stream's sid", info(N[4], m("0" * 64, N[4])), "other"),
    case("sid known: no m", info(N[4]), "other"),
    case("sid known: our i without m (a pairing i is public)", info(N[4], None, OURS), "other"),
    case("sid known: our i, wrong m", info(N[4], m("0" * 64, N[4]), OURS), "other"),
    case("sid known: m over our nonce but another identity's i", info(N[4], m(SID, N[4]), OTHER), "other"),
    case("sid known, no identity kept: m over our nonce", info(N[4], m(SID, N[4]), OTHER), "ours", identity=False),
    case("no sid yet: our i", info(N[4], None, OURS), "ours", sid=False),
    case("no sid yet: another identity's i", info(N[4], None, OTHER), "other", sid=False),
    case("no sid yet: no i (receive, don't write)", info(N[4], m(SID, N[4])), "unknown", sid=False),
    case("no sid, no identity yet (finding phones): an i", info(N[4], None, OTHER), "unknown", sid=False,
         identity=False),
]

out = {
    "about": "PROTOCOL-v2 \"Bluetooth link\" as cases (generated by link_rules.py; keys and sid from the OGS draft-1 "
    "vectors). frames: the largest frame for an ATT MTU (one ATT Write Request / notification, never a long write). "
    "long_write: what the wearer accepts as Prepare Write parts on RX and how long an unexecuted queue is kept. leave_s: "
    "how long a follower leaves a phone alone. owner: whose phone sent an INFO, given what the follower knows "
    "(identity = its stream's I, sid, the nonces of its last HELLOs). Read by Android BleLinkRulesTest (:core:protocol) "
    "and NearbyLinkRulesTest (:share), Mac BleLinkRulesTests.",
    "frames": [{"att_mtu": mtu, "max_frame": max(min(mtu - 3, ATTRIBUTE) - HEADER, MIN_PAYLOAD) + HEADER}
               for mtu in (23, 100, 185, 247, 515, 517)],
    "long_write": {"max_bytes": ATTRIBUTE, "idle_s": 30},
    "leave_s": {"other_wearer": 600, "nothing_to_pair": 5},
    "nonces_kept": len(KEPT),
    "owner": owner,
}
print(json.dumps(out, indent=1, ensure_ascii=False))
