"""The watch app's debug case loader data (cases.jungle): every case of contracts/watchface/app/cases.json (a screen
of the app drawn from one phone state of contracts/watchface/payload/cases.json's 'app' list, at a watch time) as a
Connect IQ jsonData resource (one per case, loaded only while it shows), the table of them, and the loader's manifest
(the app's own with another id and entry, so it never replaces the app). Python 3.9 stdlib only; build.sh runs it for
the 'cases' build into apps/garmin/app/build/cases/ (ignored by git: never in a release build).

  python3 apps/garmin/app/tools/cases.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
GARMIN = os.path.dirname(APP)
ROOT = os.path.dirname(os.path.dirname(GARMIN))
CASES = os.path.join(ROOT, "contracts", "watchface", "app", "cases.json")
PAYLOADS = os.path.join(ROOT, "contracts", "watchface", "payload", "cases.json")
OUT = os.path.join(APP, "build", "cases")
CASES_ID = "0c6b1f3e-5d2a-4f7e-9b8c-1a2b3c4d5e6f"
HEAD = ("Sukrara — https://github.com/mauriciabad/sukrara", "Copyright (C) 2026 Maurici Abad",
        "SPDX-License-Identifier: GPL-3.0-or-later")


def cases():
    """cases.json's cases (APP_CASES=id,id…: only those), each with its phone state's payload."""
    every = json.load(open(CASES, encoding="utf-8"))["cases"]
    states = json.load(open(PAYLOADS, encoding="utf-8"))["app"]
    only = [s for s in os.environ.get("APP_CASES", "").split(",") if s]
    out = []
    for c in every:
        if only and c["id"] not in only:
            continue
        p = dict(states[c["state"]]["payload"])
        p.update(c.get("set", {}))  # a watch state the phone's cases don't have (a high, a mute): those keys replaced
        out.append({"id": c["id"], "screen": c["screen"], "at": c.get("at", 0), "cfg": c.get("cfg", {}), "payload": p})
    return out


def main():
    res = os.path.join(OUT, "resources")
    src = os.path.join(OUT, "source")
    os.makedirs(res, exist_ok=True)
    os.makedirs(src, exist_ok=True)
    cs = cases()
    xml = ["<!-- %s -->" % h for h in HEAD] + ["<!-- Generated by apps/garmin/app/tools/cases.py. -->", "<resources>"]
    for i, c in enumerate(cs):
        name = "case%d.json" % i
        with open(os.path.join(res, name), "w", encoding="utf-8") as f:
            json.dump(c, f, ensure_ascii=False)
        xml.append('    <jsonData id="case%d" filename="%s"/>' % (i, name))
    xml.append("</resources>")
    with open(os.path.join(res, "cases.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(xml) + "\n")
    mc = ["// %s" % h for h in HEAD] + [
        "// Generated by apps/garmin/app/tools/cases.py: the case loader's table (debug builds only).",
        "import Toybox.Lang;", "", "(:debug)", "module AppCaseTable {",
        "    const COUNT = %d;" % len(cs), "",
        "    function res(i as Number) as ResourceId {",
        "        return [%s][i] as ResourceId;" % ", ".join("Rez.JsonData.case%d" % i for i in range(len(cs))),
        "    }", "}", ""]
    with open(os.path.join(src, "AppCaseTable.mc"), "w", encoding="utf-8") as f:
        f.write("\n".join(mc))
    man = open(os.path.join(APP, "manifest.xml"), encoding="utf-8").read()
    man = re.sub(r'<iq:application id="[^"]*"', '<iq:application id="%s"' % CASES_ID, man, count=1)
    man = man.replace('entry="SukraraApp"', 'entry="AppCasesApp"')
    with open(os.path.join(OUT, "manifest.xml"), "w", encoding="utf-8") as f:
        f.write(man)
    # the loader's jungle: the app's own (its watches' icon folders too) beside that manifest, its paths from here,
    # plus the loader's code and resources (a second jungle can't reset project.manifest)
    jungle = []
    for line in open(os.path.join(APP, "monkey.jungle"), encoding="utf-8"):
        line = line.rstrip("\n")
        m = re.match(r"^([\w.]+)\s*=\s*(.*)$", line)
        if not m or line.startswith("#"):
            jungle.append(line)
            continue
        key, val = m.groups()
        if key == "project.manifest":
            val = "manifest.xml"
        elif key.endswith("Path") or key.startswith("base.lang"):
            val = ";".join(p if p.startswith("$(") else "../../" + p for p in val.split(";"))
        if key == "base.sourcePath":
            val += ";../../source-cases;source"
        if key == "base.resourcePath":
            val += ";resources"
        if key == "base.excludeAnnotations":
            val = "face;field"
        jungle.append("%s = %s" % (key, val))
    with open(os.path.join(OUT, "cases.jungle"), "w", encoding="utf-8") as f:
        f.write("\n".join(jungle) + "\n")
    with open(os.path.join(OUT, "ids.json"), "w", encoding="utf-8") as f:
        json.dump([{"id": c["id"], "screen": c["screen"]} for c in cs], f)
    print("app cases:", len(cs))


if __name__ == "__main__":
    main()
