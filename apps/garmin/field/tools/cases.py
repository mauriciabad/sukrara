"""The data field's debug case loader data (build/cases/cases.jungle): every case of contracts/watchface/field/cases.json
(a form of the field, or its alert, drawn from one phone state at a watch time) as a Connect IQ jsonData resource (one per
case, loaded only while it shows), with the slots of the reference's layout for that form on the watch's screen class
(tools/watchface/app.js DFS), the table of them, and the loader's manifest (the field's own with another id and entry,
so it never replaces the field). Python 3.9 stdlib and node; build.sh runs it for the 'cases' build into
apps/garmin/field/build/cases/ (ignored by git: never in a release build).

  CIQ_DEVICE=<product> python3 apps/garmin/field/tools/cases.py
"""
import json
import os
import re
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
FIELD = os.path.dirname(HERE)
GARMIN = os.path.dirname(FIELD)
ROOT = os.path.dirname(os.path.dirname(GARMIN))
CASES = os.path.join(ROOT, "contracts", "watchface", "field", "cases.json")
APPJS = os.path.join(ROOT, "tools", "watchface", "app.js")
OUT = os.path.join(FIELD, "build", "cases")
CASES_ID = "5e0c8a3b-7d41-4c2f-9a6e-2b8d1f4c7a90"
DEVICES = os.path.expanduser(os.environ.get("CIQ_DEVICES", "~/Library/Application Support/Garmin/ConnectIQ/Devices"))
HEAD = ("Sukrara — https://github.com/mauriciabad/sukrara", "Copyright (C) 2026 Maurici Abad",
        "SPDX-License-Identifier: GPL-3.0-or-later")
FAMILY = {"round-360x360": "r360", "round-390x390": "r390", "round-416x416": "r416", "round-454x454": "r454",
          "round-466x466": "r466", "round-218x218": "m218", "round-240x240": "m240", "round-260x260": "m260",
          "round-280x280": "m280", "rectangle-320x360": "sq2", "rectangle-448x486": "x1"}


def device_class(device):
    c = json.load(open(os.path.join(DEVICES, device, "compiler.json"), encoding="utf-8"))
    return FAMILY[c["deviceFamily"]], c["resolution"]["width"], c["resolution"]["height"]


def layouts(cls):
    """The reference's slots on the class: {form: {i, f: [[x, y, w, h, obscured], …]}}."""
    js = "const W = require(%s); process.stdout.write(JSON.stringify(W.DFS[%s]));" % (json.dumps(APPJS), json.dumps(cls))
    return json.loads(subprocess.run(["node", "-e", js], check=True, capture_output=True, text=True).stdout)


def cases(device):
    """cases.json's cases (FIELD_CASES=id,id…: only those), each with its payload and its slots on [device]."""
    data = json.load(open(CASES, encoding="utf-8"))
    cls, w, h = device_class(device)
    dfs = layouts(cls)
    only = [s for s in os.environ.get("FIELD_CASES", "").split(",") if s]
    out = []
    for c in data["cases"]:
        if only and c["id"] not in only:
            continue
        form = c.get("form", "whole")
        slots = {"i": 0, "f": [[0, 0, w, h, "LTRB"]]} if form == "whole" else dfs[form]
        p = data["states"][c["state"]] if c.get("state") else None
        out.append({"id": c["id"], "screen": c["screen"], "form": form, "at": c.get("at", 0), "kind": c.get("kind"),
                    "payload": p, "slots": slots})
    return out, cls


def main():
    device = os.environ.get("CIQ_DEVICE", "descentmk343mm")
    res = os.path.join(OUT, "resources")
    src = os.path.join(OUT, "source")
    os.makedirs(res, exist_ok=True)
    os.makedirs(src, exist_ok=True)
    for d in (res, src):
        for f in os.listdir(d):
            os.remove(os.path.join(d, f))
    cs, cls = cases(device)
    xml = ["<!-- %s -->" % h for h in HEAD] + ["<!-- Generated by apps/garmin/field/tools/cases.py. -->", "<resources>"]
    for i, c in enumerate(cs):
        name = "case%d.json" % i
        with open(os.path.join(res, name), "w", encoding="utf-8") as f:
            json.dump(c, f, ensure_ascii=False)
        xml.append('    <jsonData id="case%d" filename="%s"/>' % (i, name))
    xml.append("</resources>")
    with open(os.path.join(res, "cases.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(xml) + "\n")
    mc = ["// %s" % h for h in HEAD] + [
        "// Generated by apps/garmin/field/tools/cases.py: the case loader's table (debug builds only).",
        "import Toybox.Lang;", "", "(:debug)", "module FieldCaseTable {",
        "    const COUNT = %d;" % len(cs), "",
        "    function res(i as Number) as ResourceId {",
        "        return [%s][i] as ResourceId;" % ", ".join("Rez.JsonData.case%d" % i for i in range(len(cs))),
        "    }", "}", ""]
    with open(os.path.join(src, "FieldCaseTable.mc"), "w", encoding="utf-8") as f:
        f.write("\n".join(mc))
    man = open(os.path.join(FIELD, "manifest.xml"), encoding="utf-8").read()
    man = re.sub(r'<iq:application id="[^"]*"', '<iq:application id="%s"' % CASES_ID, man, count=1)
    man = man.replace('entry="FieldApp"', 'entry="FieldCasesApp"')
    with open(os.path.join(OUT, "manifest.xml"), "w", encoding="utf-8") as f:
        f.write(man)
    # the loader's jungle: the field's own (its watches' class folders too) beside that manifest, its paths from here,
    # plus the loader's code and resources, without the field's own entry, view and alert (:fieldrun)
    jungle = []
    for line in open(os.path.join(FIELD, "monkey.jungle"), encoding="utf-8"):
        line = line.rstrip("\n")
        m = re.match(r"^([\w.]+)\s*=\s*(.*)$", line)
        if not m or line.startswith("#"):
            jungle.append(line)
            continue
        key, val = m.groups()
        if key == "project.manifest":
            val = "manifest.xml"
        elif key.endswith("Path") or key.startswith("base.lang"):
            val = ";".join(p if p.startswith("$(") else "../../" + p for p in val.split(";"))
        if key == "base.sourcePath":
            val += ";../../source-cases;source"
        if key == "base.resourcePath":
            val += ";resources"
        if key == "base.excludeAnnotations":
            val = "face;app;fieldrun"
        jungle.append("%s = %s" % (key, val))
    with open(os.path.join(OUT, "cases.jungle"), "w", encoding="utf-8") as f:
        f.write("\n".join(jungle) + "\n")
    with open(os.path.join(OUT, "ids.json"), "w", encoding="utf-8") as f:
        json.dump({"device": device, "cls": cls, "cases": [{"id": c["id"], "screen": c["screen"]} for c in cs]}, f)
    print("field cases:", len(cs), "on", device, "(%s)" % cls)


if __name__ == "__main__":
    main()
