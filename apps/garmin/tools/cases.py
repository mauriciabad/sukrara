"""The debug case loader's data: every case of contracts/watchface/aura/cases.json as a Connect IQ jsonData resource
(one per case, loaded only while it shows) and the table of them. Python 3.9 stdlib only; build.sh runs it for the
'cases' and 'test' builds into apps/garmin/build/cases/ (ignored by git: never in a release build).

  python3 apps/garmin/tools/cases.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(APP))
CASES = os.path.join(ROOT, "contracts", "watchface", "aura", "cases.json")
OUT = os.path.join(APP, "build", "cases")
HEAD = ("Sukrara — https://github.com/mauriciabad/sukrara", "Copyright (C) 2026 Maurici Abad",
        "SPDX-License-Identifier: GPL-3.0-or-later")


def main():
    cases = json.load(open(CASES, encoding="utf-8"))["cases"]
    res = os.path.join(OUT, "resources")
    src = os.path.join(OUT, "source")
    os.makedirs(res, exist_ok=True)
    os.makedirs(src, exist_ok=True)
    xml = ["<!-- %s -->" % h for h in HEAD] + ["<!-- Generated by apps/garmin/tools/cases.py. -->", "<resources>"]
    for i, c in enumerate(cases):
        name = "case%d.json" % i
        with open(os.path.join(res, name), "w", encoding="utf-8") as f:
            json.dump({"id": c["id"], "cfg": c["cfg"]}, f, ensure_ascii=False)
        xml.append('    <jsonData id="case%d" filename="%s"/>' % (i, name))
    xml.append("</resources>")
    with open(os.path.join(res, "cases.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(xml) + "\n")
    mc = ["// %s" % h for h in HEAD] + [
        "// Generated by apps/garmin/tools/cases.py from contracts/watchface/aura/cases.json (debug builds only).",
        "import Toybox.Lang;", "", "(:debug)", "module AuraCaseTable {",
        "    const COUNT = %d;" % len(cases), "",
        "    function res(i as Number) as ResourceId {",
        "        return [%s][i] as ResourceId;" % ", ".join("Rez.JsonData.case%d" % i for i in range(len(cases))),
        "    }", "}", ""]
    with open(os.path.join(src, "AuraCaseTable.mc"), "w", encoding="utf-8") as f:
        f.write("\n".join(mc))
    print("cases.py: %d cases → %s" % (len(cases), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    sys.exit(main())
