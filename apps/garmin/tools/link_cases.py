"""contracts/watchface/payload/cases.json as Monkey C, for the face's link test (test/link/LinkTest.mc).

  python3 apps/garmin/tools/link_cases.py           writes apps/garmin/test/link/LinkCases.mc
  python3 apps/garmin/tools/link_cases.py --check   fails if the committed file differs from a fresh one

apps/garmin/tools/link-test.sh runs it (with --check) before every run of the test.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
CASES = ROOT / "contracts/watchface/payload/cases.json"
OUT = ROOT / "apps/garmin/test/link/LinkCases.mc"


def mc(v):
    """A JSON value as a Monkey C literal (ints → Number, decimals → Float, objects → Dictionary)."""
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "[" + ", ".join(mc(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join("%s => %s" % (json.dumps(k), mc(x)) for k, x in v.items()) + "}"
    raise TypeError(v)


def render():
    c = json.loads(CASES.read_text())
    cases = [{"name": x["name"], "payload": x["payload"], "watch": x["watch"]} for x in c["cases"]]
    lines = [
        "// Sukrara — https://github.com/mauriciabad/sukrara",
        "// Copyright (C) 2026 Maurici Abad",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// GENERATED by apps/garmin/tools/link_cases.py from contracts/watchface/payload/cases.json: don't edit.",
        "import Toybox.Lang;",
        "",
        "(:test)",
        "module LinkCases {",
        "    const NOW = %d;" % c["now"],
        "",
        "    function cases() as Array {",
        "        return [",
    ]
    lines += ["            %s," % mc(x) for x in cases]
    lines += ["        ];", "    }", "", "    function older() as Array {", "        return ["]
    lines += ["            %s," % mc(x) for x in c["older"]["cases"]]
    lines += ["        ];", "    }", "", "    function ignored() as Array {", "        return ["]
    lines += ["            %s," % mc(x) for x in c["versions"]["ignored"]]
    lines += ["        ];", "    }", "}", ""]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("link_cases.py: %s is out of date with cases.json: run python3 apps/garmin/tools/link_cases.py" % OUT)
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(OUT)


if __name__ == "__main__":
    main()
