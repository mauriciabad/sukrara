"""contracts/watchface/payload/cases.json as Monkey C, for the SukraraFace barrel's tests (sdk/test) and the shared link's
(shared/test/link/LinkTest.mc), the
watch app's writes (entries.json, mutes.json, undos.json → app/test/WriteCases.mc, its outbox test), and the apps against the
registry (contracts/watchface/payload/apps.json).

  python3 apps/garmin/tools/link_cases.py           writes apps/garmin/sdk/test/cases/SukraraFaceCases.mc
  uv run apps/garmin/tools/link_cases.py --check    fails if the committed file differs from a fresh one, if a payload
                                                    of cases.json doesn't match schema.json (or one the apps ignore
                                                    does), or if an app's manifest (where apps.json says) has another
                                                    id or type, or its code (or the barrel's) another fetch path

apps/garmin/tools/link-test.sh runs it (with --check) before every run of the test; build.sh reads the beta ids from
apps.json itself.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
CASES = ROOT / "contracts/watchface/payload/cases.json"
APPS = ROOT / "contracts/watchface/payload/apps.json"
SCHEMA = ROOT / "contracts/watchface/payload/schema.json"
# 0BSD like the barrel whose tests read it (Sukrara's own link tests read it too)
OUT = ROOT / "apps/garmin/sdk/test/cases/SukraraFaceCases.mc"
# the watch app's writes (entries.json, mutes.json, undos.json) for its outbox test (app/test/OutboxTest.mc)
WRITES = ROOT / "apps/garmin/app/test/WriteCases.mc"


def mc(v):
    """A JSON value as a Monkey C literal (ints → Number, decimals → Float, objects → Dictionary)."""
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "[" + ", ".join(mc(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join("%s => %s" % (json.dumps(k), mc(x)) for k, x in v.items()) + "}"
    raise TypeError(v)


HEAD = [
    "// Sukrara — https://github.com/mauriciabad/sukrara",
    "// Copyright (C) 2026 Maurici Abad",
    "// SPDX-License-Identifier: GPL-3.0-or-later",
]


def render():
    c = json.loads(CASES.read_text())
    cases = [{"name": x["name"], "payload": x["payload"], "watch": x["watch"]} for x in c["cases"]]
    lines = [
        "// SukraraFace — https://sukrara.mauri.app/developers/garmin-faces/",
        "// Copyright (C) 2026 Maurici Abad",
        "// SPDX-License-Identifier: 0BSD",
        "// GENERATED by apps/garmin/tools/link_cases.py from contracts/watchface/payload/cases.json: don't edit.",
        "import Toybox.Lang;",
        "",
        "(:test)",
        "module SukraraFaceCases {",
        "    const NOW = %d;" % c["now"],
        "",
        "    function cases() as Array {",
        "        return [",
    ]
    lines += ["            %s," % mc(x) for x in cases]
    lines += ["        ];", "    }", "", "    function older() as Array {", "        return ["]
    lines += ["            %s," % mc(x) for x in c["older"]["cases"]]
    lines += ["        ];", "    }", "", "    function ignored() as Array {", "        return ["]
    lines += ["            %s," % mc(x) for x in c["versions"]["ignored"]]
    for profile in ("app", "field"):
        lines += ["        ];", "    }", "", "    function %s() as Array {" % profile, "        return ["]
        lines += ["            %s," % mc({"name": x["name"], "payload": x["payload"]}) for x in c[profile]]
    lines += ["        ];", "    }", "}", ""]
    return "\n".join(lines)


def registry():
    """What doesn't match apps.json: each app's manifest (its id and type) and the fetch path its code asks for."""
    bad = []
    reg = json.loads(APPS.read_text())
    service = (ROOT / "apps/garmin/shared/link/LinkService.mc").read_text()
    for a in reg["apps"]:
        m = ROOT / a["manifest"]
        if not m.exists():
            print("link_cases.py: pending: %s (%s)" % (a["manifest"], a["name"]))
            continue
        app = re.search(r"<iq:application\b[^>]*>", m.read_text()).group(0)
        if 'id="%s"' % a["id"] not in app:
            bad.append("%s: the id isn't apps.json's %s" % (a["manifest"], a["id"]))
        if 'type="%s"' % a["type"] not in app:
            bad.append("%s: the type isn't apps.json's %s" % (a["manifest"], a["type"]))
        want = '(:%s)\n    const FETCH_URL = "http://127.0.0.1:%d/%s";' % (a["profile"], reg["port"], a["fetch"])
        if want not in service:
            bad.append("apps/garmin/shared/link/LinkService.mc: no %s" % want.replace("\n    ", " "))
    face = next(a for a in reg["apps"] if a["profile"] == "face")
    url = 'const URL = "http://127.0.0.1:%d/%s";' % (reg["port"], face["fetch"])
    if url not in (ROOT / "apps/garmin/sdk/source/face/SukraraFaceLink.mc").read_text():
        bad.append("apps/garmin/sdk/source/face/SukraraFaceLink.mc: no %s" % url)
    # the barrel's major version is the payload's v; the sample depends on the barrel's version
    v = json.loads(SCHEMA.read_text())["oneOf"][0]["properties"]["v"]["const"]
    barrel = re.search(r'module="SukraraFace" version="([0-9.]+)"', (ROOT / "apps/garmin/sdk/manifest.xml").read_text()).group(1)
    if barrel.split(".")[0] != str(v):
        bad.append("apps/garmin/sdk/manifest.xml: version %s, but the payload is version %s" % (barrel, v))
    if "const VERSION = %d;" % v not in (ROOT / "apps/garmin/sdk/source/read/SukraraFace.mc").read_text():
        bad.append("apps/garmin/sdk/source/read/SukraraFace.mc: no const VERSION = %d;" % v)
    if '<iq:depends name="SukraraFace" version="%s"/>' % barrel not in (ROOT / "apps/garmin/sample/manifest.xml").read_text():
        bad.append("apps/garmin/sample/manifest.xml: doesn't depend on SukraraFace %s" % barrel)
    return bad


def schema():
    """What doesn't match schema.json: every payload of cases.json must, none the apps ignore may."""
    try:
        import jsonschema
    except ImportError:
        print("link_cases.py: NOTE: cases.json not checked against schema.json (no jsonschema: run it with uv run)")
        return []
    v = jsonschema.Draft202012Validator(json.loads(SCHEMA.read_text()))
    c = json.loads(CASES.read_text())
    bad = []
    for profile in ("cases", "app", "field"):
        for x in c[profile]:
            for e in v.iter_errors(x["payload"]):
                bad.append("%s: %s: %s %s" % (profile, x["name"], e.json_path, e.message[:200]))
    bad += ["versions.ignored: %s matches the schema" % json.dumps(x) for x in c["versions"]["ignored"] if v.is_valid(x)]
    return bad


def render_writes():
    p = ROOT / "contracts/watchface/payload"
    e = json.loads((p / "entries.json").read_text())
    m = json.loads((p / "mutes.json").read_text())
    u = json.loads((p / "undos.json").read_text())
    keep = ("name", "body", "signed", "answer", "stores")
    lines = HEAD + [
        "// GENERATED by apps/garmin/tools/link_cases.py from contracts/watchface/payload/entries.json, mutes.json and",
        "// undos.json: don't edit.",
        "import Toybox.Lang;",
        "",
        "(:test)",
        "module WriteCases {",
        "    const KEY = %s;" % mc(e["key"]),
        "    const NOW = %d;" % e["now"],
        "",
        "    function entries() as Array {",
        "        return [",
    ]
    lines += ["            %s," % mc({k: x[k] for k in keep if k in x}) for x in e["cases"]]
    lines += ["        ];", "    }", "", "    function mutes() as Array {", "        return ["]
    lines += ["            %s," % mc({k: x[k] for k in keep if k in x}) for x in m["cases"]]
    lines += ["        ];", "    }", "", "    function undos() as Array {", "        return ["]
    lines += ["            %s," % mc({k: x[k] for k in keep if k in x}) for x in u["cases"]]
    lines += ["        ];", "    }", "}", ""]
    return "\n".join(lines)


def main():
    text = render()
    writes = render_writes()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("link_cases.py: %s is out of date with cases.json: run python3 apps/garmin/tools/link_cases.py" % OUT)
        if not WRITES.exists() or WRITES.read_text() != writes:
            sys.exit("link_cases.py: %s is out of date with entries.json / mutes.json / undos.json: run python3 "
                     "apps/garmin/tools/link_cases.py" % WRITES)
        sys.path.insert(0, str(pathlib.Path(__file__).parent))
        import icons  # noqa: E402  (the app's complication icons per watch size)
        stale = icons.problems()
        if stale:
            sys.exit("link_cases.py: the complication icons are out of date: run python3 apps/garmin/tools/icons.py ("
                     + ", ".join(stale) + ")")
        bad = schema()
        if bad:
            sys.exit("link_cases.py: cases.json against contracts/watchface/payload/schema.json:\n  " + "\n  ".join(bad))
        bad = registry()
        if bad:
            sys.exit("link_cases.py: the apps don't match contracts/watchface/payload/apps.json:\n  " + "\n  ".join(bad))
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(OUT)
    WRITES.parent.mkdir(parents=True, exist_ok=True)
    WRITES.write_text(writes)
    print(WRITES)


if __name__ == "__main__":
    main()
