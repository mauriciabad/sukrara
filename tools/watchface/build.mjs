// Sukrara Aura: regenerate the expectations and the reference pictures from the reference implementation (aura.js).
//   node tools/watchface/build.mjs            expect.json + every PNG (needs Google Chrome; set CHROME to its binary)
//   node tools/watchface/build.mjs --json     expect.json only
//   node tools/watchface/build.mjs --case <id> [--out <file.png>] [--size 390] [--bezel] [--cfg '{"lang":"es"}']   one
//     picture; --cfg adds or replaces the case's inputs (SPEC.md §3), e.g. the same state in Spanish
// Also writes a gallery of every case to the system temp folder (printed at the end) for a quick look.

import { createRequire } from 'node:module';
import { execFile } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const require = createRequire(import.meta.url);
const Aura = require('./aura.js');
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const casesFile = path.join(root, 'contracts/watchface/aura/cases.json');
const expectFile = path.join(root, 'contracts/watchface/aura/expect.json');
const refDir = path.join(root, 'docs/img/aura/ref');
const storeDir = path.join(root, 'docs/img/aura/store');
const chrome = process.env.CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const args = process.argv.slice(2);
const flag = (f) => args.includes(f);
const opt = (f, d) => (args.includes(f) ? args[args.indexOf(f) + 1] : d);
const { cases, store } = JSON.parse(fs.readFileSync(casesFile, 'utf8'));

// The numbers a port must reproduce: everything layout() returns, minus the long path data (summarised) and the
// renderer's own ids, palette and bezel metal (SPEC.md §2 and §6 give those).
function slim(v) {
  if (Array.isArray(v)) return v.length === 1 && typeof v[0] === 'string' ? v[0] : v.map(slim);
  if (typeof v === 'string' && /^M/.test(v) && v.length > 160) return { path: (v.match(/M/g) || []).length + ' subpaths', chars: v.length };
  if (v && typeof v === 'object') {
    const o = {};
    for (const [k, x] of Object.entries(v)) if (!['ids', 'metal', 'pal'].includes(k)) o[k] = slim(x);
    return o;
  }
  return v;
}
const screen = (cfg) => Object.assign({ size: 390, bezel: false }, cfg);

function writeExpect() {
  const out = {
    about: 'Generated by tools/watchface/build.mjs from tools/watchface/aura.js: every value layout() returns for each case of cases.json at 390 px without the bezel. Coordinates have the screen centre at (0, 0) (device x = 195 + x, y = 195 + y); angles in degrees clockwise from 12 o\'clock. Long paths are summarised; regenerate rather than edit.',
    cases: cases.map((c) => ({ id: c.id, values: slim(Aura.layout(screen(c.cfg))) })),
  };
  fs.writeFileSync(expectFile, JSON.stringify(out, null, 1) + '\n');
  console.log('wrote', path.relative(root, expectFile), cases.length, 'cases');
}

function shoot(cfg, file, size) {
  const url = pathToFileURL(path.join(here, 'render.html')).href + '#cfg=' + encodeURIComponent(JSON.stringify(cfg));
  const a = ['--headless=new', '--hide-scrollbars', '--force-device-scale-factor=1', '--default-background-color=00000000',
    '--window-size=' + size + ',' + size, '--virtual-time-budget=6000', '--screenshot=' + file, url];
  return new Promise((res, rej) => execFile(chrome, a, { timeout: 60000 }, (e) => (e ? rej(e) : res())));
}

async function pool(jobs, n) {
  let i = 0;
  await Promise.all(Array.from({ length: n }, async () => { while (i < jobs.length) { const j = jobs[i++]; await j(); } }));
}

function gallery() {
  const items = cases.map((c) => '<figure><div>' + Aura.svg(Object.assign({ size: 260, bezel: true }, c.cfg)) + '</div><figcaption><b>' + c.id + '</b><br>' + c.expect + '</figcaption></figure>').join('\n');
  const html = '<!doctype html><meta charset="utf-8"><title>Sukrara Aura cases</title><link href="https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible+Next:wght@400;500;600;700&family=Barlow+Semi+Condensed:wght@500;600&display=swap" rel="stylesheet"><style>body{background:#111;color:#ddd;font:13px system-ui;display:grid;grid-template-columns:repeat(auto-fill,280px);gap:16px;padding:16px}figure{margin:0}</style>' + items;
  const f = path.join(os.tmpdir(), 'sukrara-aura-gallery.html');
  fs.writeFileSync(f, html);
  console.log('gallery', f);
}

if (flag('--case')) {
  const id = opt('--case');
  const c = cases.find((x) => x.id === id) || store.find((x) => x.id === id);
  if (!c) throw new Error('no case ' + id);
  const size = Number(opt('--size', flag('--bezel') ? 1168 : 390));
  const file = path.resolve(opt('--out', id + '.png'));
  await shoot(Object.assign({ size, bezel: flag('--bezel') }, c.cfg, JSON.parse(opt('--cfg', '{}'))), file, size);
  console.log('wrote', file);
} else {
  writeExpect();
  if (!flag('--json')) {
    fs.mkdirSync(refDir, { recursive: true });
    fs.mkdirSync(storeDir, { recursive: true });
    const jobs = cases.map((c) => () => shoot(screen(c.cfg), path.join(refDir, c.id + '.png'), 390))
      .concat(store.map((s) => () => shoot(Object.assign({ size: 1168, bezel: true }, s.cfg), path.join(storeDir, s.id + '.png'), 1168)));
    await pool(jobs, 4);
    console.log('wrote', cases.length, 'reference and', store.length, 'store pictures');
  }
  gallery();
}
